import math

def f(x):
    return math.exp(-x**2)

def trapeze_composite(f, a, b, n):
    h = (b - a) / n
    S = f(a) + f(b)

    for i in range(1, n):
        x = a + i * h
        S += 2 * f(x)

    return h * S / 2


